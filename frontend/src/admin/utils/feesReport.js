import * as XLSX from "xlsx";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

const SCHOOL_NAME = "School Management System";
const REPORT_FOOTER = "Confidential — Generated by School Management System";

const inrFormatter = new Intl.NumberFormat("en-IN", {
  style: "currency",
  currency: "INR",
  maximumFractionDigits: 0,
});

const numberFormatter = new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 });

// Used in Excel (supports ₹ in spreadsheet apps) and in UI notifications
const formatCurrency = (value = 0) => inrFormatter.format(Number(value) || 0);
const formatNumber = (value = 0) => numberFormatter.format(Number(value) || 0);

// jsPDF's built-in Helvetica is Latin-1 and cannot render ₹. Use "Rs." instead.
const pdfNumberFormatter = new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 });
const formatCurrencyPdf = (value = 0) => `Rs. ${pdfNumberFormatter.format(Number(value) || 0)}`;

const formatDateLong = (date = new Date()) =>
  new Date(date).toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });

const formatDateForFile = (date = new Date()) => {
  const value = new Date(date);
  const year = value.getFullYear();
  const month = String(value.getMonth() + 1).padStart(2, "0");
  const day = String(value.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
};

const sanitizeFileName = (value = "") =>
  String(value || "report")
    .trim()
    .replace(/[^a-z0-9_-]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase() || "report";

const getStudentName = (student = {}) =>
  student.name ||
  `${student.firstName || ""} ${student.lastName || ""}`.trim() ||
  "Student";

const getParentName = (student = {}) =>
  student.parent?.fatherName ||
  student.parentName ||
  student.parent?.motherName ||
  "N/A";

const getParentPhone = (student = {}) =>
  student.parent?.phone || student.parentPhone || student.phone || "N/A";

const getStatusLabel = (status = "") => {
  const value = String(status || "pending").toLowerCase();
  return value.charAt(0).toUpperCase() + value.slice(1);
};

const buildStatusBuckets = (students = []) => {
  const buckets = { paid: 0, partial: 0, pending: 0, overdue: 0 };
  students.forEach((student) => {
    const key = String(student.status || "pending").toLowerCase();
    if (buckets[key] === undefined) buckets[key] = 0;
    buckets[key] += 1;
  });
  return buckets;
};

const buildStudentRows = (students = []) =>
  students.map((student, index) => ({
    index: index + 1,
    name: getStudentName(student),
    admissionNo: student.admissionNo || student.studentId || "N/A",
    parent: getParentName(student),
    phone: getParentPhone(student),
    total: Number(student.totalFees || 0),
    paid: Number(student.paidAmount || 0),
    pending: Number(student.pendingAmount || 0),
    status: getStatusLabel(student.status),
  }));

export const exportClassFeesExcel = (summary = {}) => {
  if (!summary || !Array.isArray(summary.students)) return;

  const className = summary.label || "Class";
  const generatedAt = new Date();
  const students = buildStudentRows(summary.students);
  const buckets = buildStatusBuckets(summary.students);

  const workbook = XLSX.utils.book_new();

  // Sheet 1: Summary
  const summaryAoa = [
    [SCHOOL_NAME],
    [`Class Fees Report — ${className}`],
    [`Generated: ${formatDateLong(generatedAt)}`],
    [],
    ["Metric", "Value"],
    ["Students", summary.studentCount || students.length],
    ["Total Fees", Number(summary.totalDue || 0)],
    ["Collected", Number(summary.totalCollected || 0)],
    ["Pending", Number(summary.totalPending || 0)],
    [
      "Collection Rate (%)",
      Number(summary.collectionRate || 0),
    ],
    [],
    ["Status Breakdown", "Count"],
    ["Paid", buckets.paid || 0],
    ["Partial", buckets.partial || 0],
    ["Pending", buckets.pending || 0],
    ["Overdue", buckets.overdue || 0],
  ];

  const fees = summary.classItem?.fees || {};
  if (fees && (fees.tuition || fees.admission || fees.exam || fees.books)) {
    summaryAoa.push([]);
    summaryAoa.push(["Fee Component", "Amount (per student)"]);
    if (fees.tuition !== undefined) summaryAoa.push(["Tuition", Number(fees.tuition || 0)]);
    if (fees.admission !== undefined) summaryAoa.push(["Admission", Number(fees.admission || 0)]);
    if (fees.exam !== undefined) summaryAoa.push(["Exam", Number(fees.exam || 0)]);
    if (fees.books !== undefined) summaryAoa.push(["Books", Number(fees.books || 0)]);
  }

  const summarySheet = XLSX.utils.aoa_to_sheet(summaryAoa);
  summarySheet["!cols"] = [{ wch: 28 }, { wch: 22 }];
  summarySheet["!merges"] = [
    { s: { r: 0, c: 0 }, e: { r: 0, c: 1 } },
    { s: { r: 1, c: 0 }, e: { r: 1, c: 1 } },
    { s: { r: 2, c: 0 }, e: { r: 2, c: 1 } },
  ];
  XLSX.utils.book_append_sheet(workbook, summarySheet, "Summary");

  // Sheet 2: Students
  const studentHeader = [
    "#",
    "Student Name",
    "Admission No",
    "Parent",
    "Phone",
    "Total Fees",
    "Paid",
    "Pending",
    "Status",
  ];
  const studentAoa = [
    [SCHOOL_NAME],
    [`${className} — Student Fees`],
    [`Generated: ${formatDateLong(generatedAt)}`],
    [],
    studentHeader,
    ...students.map((student) => [
      student.index,
      student.name,
      student.admissionNo,
      student.parent,
      student.phone,
      student.total,
      student.paid,
      student.pending,
      student.status,
    ]),
  ];

  // Append totals row
  studentAoa.push([
    "",
    "TOTAL",
    "",
    "",
    "",
    students.reduce((sum, student) => sum + student.total, 0),
    students.reduce((sum, student) => sum + student.paid, 0),
    students.reduce((sum, student) => sum + student.pending, 0),
    "",
  ]);

  const studentSheet = XLSX.utils.aoa_to_sheet(studentAoa);
  studentSheet["!cols"] = [
    { wch: 5 },
    { wch: 28 },
    { wch: 14 },
    { wch: 24 },
    { wch: 16 },
    { wch: 14 },
    { wch: 14 },
    { wch: 14 },
    { wch: 12 },
  ];
  studentSheet["!merges"] = [
    { s: { r: 0, c: 0 }, e: { r: 0, c: 8 } },
    { s: { r: 1, c: 0 }, e: { r: 1, c: 8 } },
    { s: { r: 2, c: 0 }, e: { r: 2, c: 8 } },
  ];

  // Apply INR number format to currency columns (F..H), data rows start at row 6 (index 5)
  const totalRows = studentAoa.length;
  for (let rowIndex = 5; rowIndex < totalRows; rowIndex += 1) {
    ["F", "G", "H"].forEach((column) => {
      const cellRef = `${column}${rowIndex + 1}`;
      const cell = studentSheet[cellRef];
      if (cell && typeof cell.v === "number") {
        cell.t = "n";
        cell.z = '"₹"#,##0';
      }
    });
  }

  XLSX.utils.book_append_sheet(workbook, studentSheet, "Students");

  const fileName = `${sanitizeFileName(className)}-fees-${formatDateForFile(generatedAt)}.xlsx`;
  XLSX.writeFile(workbook, fileName);
};

const drawHeaderBlock = (doc, { className, generatedAt, pageWidth }) => {
  // Top brand bar
  doc.setFillColor(37, 99, 235);
  doc.rect(0, 0, pageWidth, 24, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(SCHOOL_NAME, 14, 11);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text("Fees Report", 14, 18);

  doc.setFontSize(9);
  doc.text(`Generated: ${formatDateLong(generatedAt)}`, pageWidth - 14, 11, { align: "right" });
  doc.text(`Class: ${className}`, pageWidth - 14, 18, { align: "right" });

  // Title
  doc.setTextColor(15, 23, 42);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text(`${className} — Fees Report`, 14, 36);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text(
    "Detailed fees ledger and collection summary for all students enrolled in this class.",
    14,
    42
  );
};

const drawStatTile = (doc, { x, y, width, height, label, value, accent }) => { // value must be PDF-safe (no ₹)
  doc.setDrawColor(226, 232, 240);
  doc.setFillColor(accent[0], accent[1], accent[2]);
  doc.roundedRect(x, y, width, height, 2, 2, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text(String(label).toUpperCase(), x + 4, y + 6);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(String(value), x + 4, y + 16);
};

const drawFooter = (doc, pageWidth, pageHeight) => {
  const totalPages = doc.internal.getNumberOfPages();
  for (let pageIndex = 1; pageIndex <= totalPages; pageIndex += 1) {
    doc.setPage(pageIndex);
    doc.setDrawColor(226, 232, 240);
    doc.line(14, pageHeight - 12, pageWidth - 14, pageHeight - 12);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(REPORT_FOOTER, 14, pageHeight - 6);
    doc.text(
      `Page ${pageIndex} of ${totalPages}`,
      pageWidth - 14,
      pageHeight - 6,
      { align: "right" }
    );
  }
};

export const exportClassFeesPdf = (summary = {}) => {
  if (!summary || !Array.isArray(summary.students)) return;

  const className = summary.label || "Class";
  const generatedAt = new Date();
  const students = buildStudentRows(summary.students);
  const buckets = buildStatusBuckets(summary.students);

  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  drawHeaderBlock(doc, { className, generatedAt, pageWidth });

  // KPI tiles
  const tileY = 50;
  const tileHeight = 22;
  const tileGap = 4;
  const tileWidth = (pageWidth - 28 - tileGap * 3) / 4;

  drawStatTile(doc, {
    x: 14,
    y: tileY,
    width: tileWidth,
    height: tileHeight,
    label: "Students",
    value: formatNumber(summary.studentCount || students.length),
    accent: [241, 245, 249],
  });
  drawStatTile(doc, {
    x: 14 + tileWidth + tileGap,
    y: tileY,
    width: tileWidth,
    height: tileHeight,
    label: "Total Fees",
    value: formatCurrencyPdf(summary.totalDue),
    accent: [239, 246, 255],
  });
  drawStatTile(doc, {
    x: 14 + (tileWidth + tileGap) * 2,
    y: tileY,
    width: tileWidth,
    height: tileHeight,
    label: "Collected",
    value: formatCurrencyPdf(summary.totalCollected),
    accent: [240, 253, 244],
  });
  drawStatTile(doc, {
    x: 14 + (tileWidth + tileGap) * 3,
    y: tileY,
    width: tileWidth,
    height: tileHeight,
    label: "Pending",
    value: formatCurrencyPdf(summary.totalPending),
    accent: [255, 251, 235],
  });

  // Collection rate bar
  const barY = tileY + tileHeight + 8;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(15, 23, 42);
  doc.text("Collection Progress", 14, barY);

  const rate = Math.min(Math.max(Number(summary.collectionRate || 0), 0), 100);
  const barX = 14;
  const barWidth = pageWidth - 28;
  const barHeight = 6;
  const barTop = barY + 3;

  doc.setFillColor(241, 245, 249);
  doc.roundedRect(barX, barTop, barWidth, barHeight, 1.5, 1.5, "F");
  doc.setFillColor(34, 197, 94);
  doc.roundedRect(barX, barTop, (barWidth * rate) / 100, barHeight, 1.5, 1.5, "F");

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`${rate}% collected`, barX, barTop + barHeight + 5);

  // Status breakdown table
  const statusTableTop = barTop + barHeight + 10;
  autoTable(doc, {
    startY: statusTableTop,
    head: [["Status", "Students", "Share"]],
    body: [
      ["Paid", formatNumber(buckets.paid || 0), `${students.length ? Math.round(((buckets.paid || 0) * 100) / students.length) : 0}%`],
      ["Partial", formatNumber(buckets.partial || 0), `${students.length ? Math.round(((buckets.partial || 0) * 100) / students.length) : 0}%`],
      ["Pending", formatNumber(buckets.pending || 0), `${students.length ? Math.round(((buckets.pending || 0) * 100) / students.length) : 0}%`],
      ["Overdue", formatNumber(buckets.overdue || 0), `${students.length ? Math.round(((buckets.overdue || 0) * 100) / students.length) : 0}%`],
    ],
    theme: "grid",
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5, textColor: [30, 41, 59] },
    headStyles: { fillColor: [248, 250, 252], textColor: [51, 65, 85], fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 40 },
      1: { halign: "right", cellWidth: 30 },
      2: { halign: "right", cellWidth: 30 },
    },
    margin: { left: 14, right: pageWidth - 14 - 100 },
  });

  // Fee structure (right column beside status table)
  const fees = summary.classItem?.fees || {};
  const feeStructureRows = [];
  if (fees.tuition !== undefined) feeStructureRows.push(["Tuition", formatCurrencyPdf(fees.tuition)]);
  if (fees.admission !== undefined) feeStructureRows.push(["Admission", formatCurrencyPdf(fees.admission)]);
  if (fees.exam !== undefined) feeStructureRows.push(["Exam", formatCurrencyPdf(fees.exam)]);
  if (fees.books !== undefined) feeStructureRows.push(["Books", formatCurrencyPdf(fees.books)]);

  if (feeStructureRows.length > 0) {
    autoTable(doc, {
      startY: statusTableTop,
      head: [["Fee Component", "Per Student"]],
      body: feeStructureRows,
      theme: "grid",
      styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5, textColor: [30, 41, 59] },
      headStyles: { fillColor: [248, 250, 252], textColor: [51, 65, 85], fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 45 },
        1: { halign: "right", cellWidth: 40 },
      },
      margin: { left: pageWidth - 14 - 85, right: 14 },
    });
  }

  // Student detail table
  const lastStatusY = doc.lastAutoTable?.finalY || statusTableTop + 40;
  const detailTop = lastStatusY + 10;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text("Student Ledger", 14, detailTop);

  autoTable(doc, {
    startY: detailTop + 3,
    head: [["#", "Student", "Adm. No", "Parent", "Phone", "Total", "Paid", "Pending", "Status"]],
    body: students.map((student) => [
      student.index,
      student.name,
      student.admissionNo,
      student.parent,
      student.phone,
      formatCurrencyPdf(student.total),
      formatCurrencyPdf(student.paid),
      formatCurrencyPdf(student.pending),
      student.status,
    ]),
    foot: [
      [
        "",
        { content: "TOTAL", styles: { fontStyle: "bold" } },
        "",
        "",
        "",
        {
          content: formatCurrencyPdf(students.reduce((sum, student) => sum + student.total, 0)),
          styles: { fontStyle: "bold", halign: "right" },
        },
        {
          content: formatCurrencyPdf(students.reduce((sum, student) => sum + student.paid, 0)),
          styles: { fontStyle: "bold", halign: "right", textColor: [22, 101, 52] },
        },
        {
          content: formatCurrencyPdf(students.reduce((sum, student) => sum + student.pending, 0)),
          styles: { fontStyle: "bold", halign: "right", textColor: [185, 28, 28] },
        },
        "",
      ],
    ],
    showFoot: "lastPage",
    theme: "striped",
    styles: { font: "helvetica", fontSize: 8.5, cellPadding: 2, textColor: [30, 41, 59] },
    headStyles: {
      fillColor: [37, 99, 235],
      textColor: [255, 255, 255],
      fontStyle: "bold",
      halign: "left",
    },
    footStyles: { fillColor: [248, 250, 252], textColor: [15, 23, 42], fontStyle: "bold" },
    alternateRowStyles: { fillColor: [249, 250, 251] },
    columnStyles: {
      0: { cellWidth: 6, halign: "right" },
      1: { cellWidth: 32 },
      2: { cellWidth: 16 },
      3: { cellWidth: 24 },
      4: { cellWidth: 18 },
      5: { halign: "right", cellWidth: 25 },
      6: { halign: "right", cellWidth: 25, textColor: [22, 101, 52] },
      7: { halign: "right", cellWidth: 25, textColor: [185, 28, 28] },
      8: { cellWidth: 11 },
    },
    didParseCell: (data) => {
      if (data.section === "body" && data.column.index === 8) {
        const status = String(data.cell.raw || "").toLowerCase();
        if (status === "paid") {
          data.cell.styles.textColor = [22, 101, 52];
          data.cell.styles.fontStyle = "bold";
        } else if (status === "partial") {
          data.cell.styles.textColor = [29, 78, 216];
          data.cell.styles.fontStyle = "bold";
        } else if (status === "overdue") {
          data.cell.styles.textColor = [185, 28, 28];
          data.cell.styles.fontStyle = "bold";
        } else if (status === "pending") {
          data.cell.styles.textColor = [180, 83, 9];
          data.cell.styles.fontStyle = "bold";
        }
      }
    },
    margin: { left: 14, right: 14 },
  });

  drawFooter(doc, pageWidth, pageHeight);

  const fileName = `${sanitizeFileName(className)}-fees-${formatDateForFile(generatedAt)}.pdf`;
  doc.save(fileName);
};
