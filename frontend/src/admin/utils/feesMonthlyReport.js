import * as XLSX from "xlsx";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

const SCHOOL_NAME = "School Management System";
const REPORT_FOOTER = "Confidential — Generated by School Management System";

// jsPDF helvetica is Latin-1; the ₹ glyph renders as an apostrophe. Use "Rs." for PDF.
const numberFormatter = new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 });
const formatCurrencyPdf = (value = 0) => `Rs. ${numberFormatter.format(Number(value) || 0)}`;
const inrFormatter = new Intl.NumberFormat("en-IN", {
  style: "currency",
  currency: "INR",
  maximumFractionDigits: 0,
});
const formatCurrencyExcel = (value = 0) => inrFormatter.format(Number(value) || 0);

const formatDateLong = (date = new Date()) =>
  new Date(date).toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });

const formatDateForFile = (date = new Date()) => {
  const value = new Date(date);
  const year = value.getFullYear();
  const month = String(value.getMonth() + 1).padStart(2, "0");
  const day = String(value.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
};

const sanitizeFileName = (value = "") =>
  String(value || "report")
    .trim()
    .replace(/[^a-z0-9_-]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase() || "report";

const getStatusLabel = (status = "") => {
  const value = String(status || "pending").toLowerCase();
  return value.charAt(0).toUpperCase() + value.slice(1);
};

const STATUS_COLORS = {
  paid: [22, 101, 52],
  partial: [29, 78, 216],
  pending: [180, 83, 9],
  overdue: [185, 28, 28],
};

const getStatusColor = (status) => STATUS_COLORS[String(status || "").toLowerCase()] || [71, 85, 105];

const buildPeriodLabel = (months = []) => {
  if (!Array.isArray(months) || months.length === 0) return "";
  if (months.length === 1) return months[0].monthLabel;
  if (months.length === 12) return "Full Academic Year (Apr – Mar)";
  return `${months[0].monthLabel} – ${months[months.length - 1].monthLabel}`;
};

