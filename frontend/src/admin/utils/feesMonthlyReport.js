const drawBrandBar = (doc, pageWidth, classLabel, academicYear, periodLabel) => {
  doc.setFillColor(37, 99, 235);
  doc.rect(0, 0, pageWidth, 26, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(SCHOOL_NAME, 14, 11);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text("Monthly Fees Report", 14, 18);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(`Generated: ${formatDateLong()}`, pageWidth - 14, 11, { align: "right" });
  if (academicYear) {
    doc.text(`Academic Year: ${academicYear}`, pageWidth - 14, 17, { align: "right" });
  }
  if (periodLabel) {
    doc.text(`Period: ${periodLabel}`, pageWidth - 14, 23, { align: "right" });
  }
  if (classLabel) {
    doc.text(`Class: ${classLabel}`, 14, 23);
  }
};

const drawFooter = (doc, pageWidth, pageHeight) => {
  const totalPages = doc.internal.getNumberOfPages();
  for (let pageIndex = 1; pageIndex <= totalPages; pageIndex += 1) {
    doc.setPage(pageIndex);
    doc.setDrawColor(226, 232, 240);
    doc.line(14, pageHeight - 12, pageWidth - 14, pageHeight - 12);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(REPORT_FOOTER, 14, pageHeight - 6);
    doc.text(`Page ${pageIndex} of ${totalPages}`, pageWidth - 14, pageHeight - 6, {
      align: "right",
    });
  }
};

const drawStatTile = (doc, { x, y, width, height, label, value, accent }) => {
  doc.setDrawColor(226, 232, 240);
  doc.setFillColor(accent[0], accent[1], accent[2]);
  doc.roundedRect(x, y, width, height, 2, 2, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text(String(label).toUpperCase(), x + 4, y + 6);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(String(value), x + 4, y + 16);
};

export const exportMonthlyClassPdf = ({ classLabel = "Class", report }) => {
  if (!report || !Array.isArray(report.students)) {
    throw new Error("Invalid report data");
  }

  const months = report.months || [];
  const periodLabel = buildPeriodLabel(months);
  const academicYear = report.academicYear || "";

  // For wide reports (many months), switch to landscape A4.
  const orientation = months.length > 4 ? "landscape" : "portrait";
  const doc = new jsPDF({ orientation, unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  drawBrandBar(doc, pageWidth, classLabel, academicYear, periodLabel);

  // Title
  let cursorY = 36;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.setTextColor(15, 23, 42);
  doc.text(`${classLabel} — Monthly Fees Report`, 14, cursorY);

  cursorY += 5;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text(
    `Detailed monthly fees status for ${months.length} month${months.length === 1 ? "" : "s"} (${periodLabel}).`,
    14,
    cursorY
  );

  // KPI tiles
  cursorY += 8;
  const tileGap = 4;
  const tileHeight = 20;
  const tileCount = 4;
  const tileWidth = (pageWidth - 28 - tileGap * (tileCount - 1)) / tileCount;
  drawStatTile(doc, {
    x: 14,
    y: cursorY,
    width: tileWidth,
    height: tileHeight,
    label: "Students",
    value: numberFormatter.format(report.classTotals?.studentCount || 0),
    accent: [241, 245, 249],
  });
  drawStatTile(doc, {
    x: 14 + tileWidth + tileGap,
    y: cursorY,
    width: tileWidth,
    height: tileHeight,
    label: "Total Fees",
    value: formatCurrencyPdf(report.classTotals?.totalDue),
    accent: [239, 246, 255],
  });
  drawStatTile(doc, {
    x: 14 + (tileWidth + tileGap) * 2,
    y: cursorY,
    width: tileWidth,
    height: tileHeight,
    label: "Collected",
    value: formatCurrencyPdf(report.classTotals?.totalPaid),
    accent: [240, 253, 244],
  });
  drawStatTile(doc, {
    x: 14 + (tileWidth + tileGap) * 3,
    y: cursorY,
    width: tileWidth,
    height: tileHeight,
    label: "Pending",
    value: formatCurrencyPdf(report.classTotals?.totalPending),
    accent: [255, 251, 235],
  });

  cursorY += tileHeight + 8;

  // Per-month summary band (one row per month)
  autoTable(doc, {
    startY: cursorY,
    head: [["Month", "Due Date", "Total Due", "Collected", "Pending", "Collection %"]],
    body: months.map((month) => {
      const agg = report.students.reduce(
        (acc, student) => {
          const m = (student.monthlyBreakdown || []).find(
            (entry) => entry.monthKey === month.monthKey
          );
          if (m) {
            acc.due += Number(m.totalDue) || 0;
            acc.paid += Number(m.paidAmount) || 0;
            acc.pending += Number(m.endingBalance) || 0;
          }
          return acc;
        },
        { due: 0, paid: 0, pending: 0 }
      );
      const pct = agg.due > 0 ? Math.round((agg.paid / agg.due) * 100) : 0;
      return [
        month.monthLabel,
        month.dueDate ? new Date(month.dueDate).toLocaleDateString("en-IN") : "—",
        formatCurrencyPdf(agg.due),
        formatCurrencyPdf(agg.paid),
        formatCurrencyPdf(agg.pending),
        `${pct}%`,
      ];
    }),
    theme: "grid",
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.2, textColor: [30, 41, 59] },
    headStyles: {
      fillColor: [37, 99, 235],
      textColor: [255, 255, 255],
      fontStyle: "bold",
      halign: "left",
    },
    columnStyles: {
      0: { cellWidth: 28 },
      1: { cellWidth: 26 },
      2: { halign: "right" },
      3: { halign: "right", textColor: [22, 101, 52] },
      4: { halign: "right", textColor: [185, 28, 28] },
      5: { halign: "right" },
    },
    margin: { left: 14, right: 14 },
  });

  cursorY = doc.lastAutoTable.finalY + 8;

  // Compact student summary; month-level details are shown in the table above.
  const matrixHead = [
    [
      { content: "#", styles: { halign: "center" } },
      { content: "Student", styles: { halign: "left" } },
      { content: "Adm No", styles: { halign: "left" } },
      { content: "Total Due\n(Rs.)", styles: { halign: "right" } },
      { content: "Pending\n(Rs.)", styles: { halign: "right" } },
      { content: "Status", styles: { halign: "center" } },
    ],
  ];

  const matrixBody = report.students.map((student, index) => [
    { content: String(index + 1), styles: { halign: "center" } },
    student.name,
    student.admissionNo,
    {
      content: formatCurrencyPdf(student.reportTotals?.totalDue),
      styles: { halign: "right" },
    },
    {
      content: formatCurrencyPdf(student.reportTotals?.pendingAmount),
      styles: { halign: "right", textColor: [185, 28, 28] },
    },
    {
      content: getStatusLabel(student.overallStatus),
      styles: {
        halign: "center",
        textColor: getStatusColor(student.overallStatus),
        fontStyle: "bold",
      },
    },
  ]);

  // Footer total row
  const footerRow = [
    { content: "", styles: {} },
    { content: "TOTAL", styles: { fontStyle: "bold" } },
    { content: "", styles: {} },
    {
      content: formatCurrencyPdf(report.classTotals?.totalDue),
      styles: { halign: "right", fontStyle: "bold" },
    },
    {
      content: formatCurrencyPdf(report.classTotals?.totalPending),
      styles: { halign: "right", fontStyle: "bold", textColor: [185, 28, 28] },
    },
    { content: "", styles: {} },
  ];

  // Rebalance the remaining columns across the full usable page width.
  const usableWidth = pageWidth - 28;
  const columnStyles = {
    0: { cellWidth: usableWidth * 0.06, halign: "center" },
    1: { cellWidth: usableWidth * 0.31 },
    2: { cellWidth: usableWidth * 0.18 },
    3: { cellWidth: usableWidth * 0.17, halign: "right" },
    4: {
      cellWidth: usableWidth * 0.17,
      halign: "right",
      textColor: [185, 28, 28],
    },
    5: { cellWidth: usableWidth * 0.11, halign: "center" },
  };

  autoTable(doc, {
    startY: cursorY,
    head: matrixHead,
    body: matrixBody,
    foot: [footerRow],
    showFoot: "lastPage",
    theme: "striped",
    styles: { font: "helvetica", fontSize: 8.5, cellPadding: 2.2, textColor: [30, 41, 59] },
    headStyles: {
      fillColor: [37, 99, 235],
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 8,
      halign: "left",
    },
    footStyles: { fillColor: [248, 250, 252], textColor: [15, 23, 42], fontStyle: "bold" },
    alternateRowStyles: { fillColor: [249, 250, 251] },
    columnStyles,
    margin: { left: 14, right: 14, bottom: 16 },
  });

  drawFooter(doc, pageWidth, pageHeight);

  const fileName = `monthly-fees-${sanitizeFileName(classLabel)}-${formatDateForFile()}.pdf`;
  doc.save(fileName);
};
