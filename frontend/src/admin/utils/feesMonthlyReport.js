export const exportMonthlyClassExcel = ({ classLabel = "Class", report }) => {
  if (!report || !Array.isArray(report.students)) {
    throw new Error("Invalid report data");
  }

  const months = report.months || [];
  const periodLabel = buildPeriodLabel(months);
  const wb = XLSX.utils.book_new();

  // ---- Sheet 1: Summary ----
  const summarySheet = XLSX.utils.aoa_to_sheet([
    [SCHOOL_NAME],
    ["Monthly Fees Report"],
    [],
    ["Class", classLabel],
    ["Academic Year", report.academicYear || "—"],
    ["Reporting Period", periodLabel],
    ["Months Included", months.map((m) => m.monthLabel).join(", ")],
    ["Generated On", formatDateLong()],
    [],
    ["Total Students", report.classTotals?.studentCount || 0],
    ["Total Fees (selected months)", formatCurrencyExcel(report.classTotals?.totalDue)],
    ["Collected", formatCurrencyExcel(report.classTotals?.totalPaid)],
    ["Pending", formatCurrencyExcel(report.classTotals?.totalPending)],
    ["Collection Rate", `${report.classTotals?.collectionRate || 0}%`],
  ]);
  summarySheet["!cols"] = [{ wch: 28 }, { wch: 36 }];
  XLSX.utils.book_append_sheet(wb, summarySheet, "Summary");

  // ---- Sheet 2: Student × Month Matrix (compact view) ----
  const matrixHeader = ["#", "Student", "Adm No", "Parent", "Phone"];
  months.forEach((month) => {
    matrixHeader.push(`${month.monthLabel} Due`);
    matrixHeader.push(`${month.monthLabel} Paid`);
    matrixHeader.push(`${month.monthLabel} Pending`);
    matrixHeader.push(`${month.monthLabel} Status`);
  });
  matrixHeader.push("Total Due", "Total Paid", "Total Pending", "Overall Status");

  const matrixRows = report.students.map((student, index) => {
    const row = [
      index + 1,
      student.name,
      student.admissionNo,
      student.parentName,
      student.phone,
    ];
    months.forEach((month) => {
      const m = (student.monthlyBreakdown || []).find((entry) => entry.monthKey === month.monthKey) || {
        totalDue: 0,
        paidAmount: 0,
        endingBalance: 0,
        status: "pending",
      };
      row.push(Number(m.totalDue) || 0);
      row.push(Number(m.paidAmount) || 0);
      row.push(Number(m.endingBalance) || 0);
      row.push(getStatusLabel(m.status));
    });
    row.push(
      Number(student.reportTotals?.totalDue) || 0,
      Number(student.reportTotals?.paidAmount) || 0,
      Number(student.reportTotals?.pendingAmount) || 0,
      getStatusLabel(student.overallStatus)
    );
    return row;
  });

  // Footer total row
  const totalsRow = ["", "TOTAL", "", "", ""];
  months.forEach((month) => {
    const aggregate = report.students.reduce(
      (acc, student) => {
        const m = (student.monthlyBreakdown || []).find((entry) => entry.monthKey === month.monthKey);
        if (m) {
          acc.due += Number(m.totalDue) || 0;
          acc.paid += Number(m.paidAmount) || 0;
          acc.pending += Number(m.endingBalance) || 0;
        }
        return acc;
      },
      { due: 0, paid: 0, pending: 0 }
    );
    totalsRow.push(aggregate.due, aggregate.paid, aggregate.pending, "");
  });
  totalsRow.push(
    Number(report.classTotals?.totalDue) || 0,
    Number(report.classTotals?.totalPaid) || 0,
    Number(report.classTotals?.totalPending) || 0,
    ""
  );

  const matrixSheet = XLSX.utils.aoa_to_sheet([matrixHeader, ...matrixRows, totalsRow]);

  // Set column widths
  const matrixCols = [
    { wch: 4 },
    { wch: 26 },
    { wch: 12 },
    { wch: 24 },
    { wch: 14 },
  ];
  months.forEach(() => {
    matrixCols.push({ wch: 14 }, { wch: 14 }, { wch: 14 }, { wch: 10 });
  });
  matrixCols.push({ wch: 16 }, { wch: 16 }, { wch: 16 }, { wch: 12 });
  matrixSheet["!cols"] = matrixCols;

  // INR formatting for numeric currency cells
  const currencyFmt = '_-₹* #,##0_-;-₹* #,##0_-;_-₹* "-"_-;_-@_-';
  const totalRowIndex = matrixRows.length + 1; // header is row 0, data starts at row 1
  for (let r = 1; r <= matrixRows.length + 1; r += 1) {
    months.forEach((_, monthIndex) => {
      const baseCol = 5 + monthIndex * 4;
      [baseCol, baseCol + 1, baseCol + 2].forEach((c) => {
        const ref = XLSX.utils.encode_cell({ c, r });
        if (matrixSheet[ref] && typeof matrixSheet[ref].v === "number") {
          matrixSheet[ref].z = currencyFmt;
        }
      });
    });
    const totalsBaseCol = 5 + months.length * 4;
    [totalsBaseCol, totalsBaseCol + 1, totalsBaseCol + 2].forEach((c) => {
      const ref = XLSX.utils.encode_cell({ c, r });
      if (matrixSheet[ref] && typeof matrixSheet[ref].v === "number") {
        matrixSheet[ref].z = currencyFmt;
      }
    });
  }
  void totalRowIndex;

  matrixSheet["!freeze"] = { xSplit: 5, ySplit: 1 };
  XLSX.utils.book_append_sheet(wb, matrixSheet, "Monthly Matrix");

  // ---- Sheet 3: Detailed per-student-per-month ledger ----
  const ledgerHeader = [
    "Student",
    "Adm No",
    "Parent",
    "Phone",
    "Month",
    "Due Date",
    "Total Due",
    "Paid",
    "Pending",
    "Status",
  ];
  const ledgerRows = [];
  report.students.forEach((student) => {
    (student.monthlyBreakdown || []).forEach((month) => {
      ledgerRows.push([
        student.name,
        student.admissionNo,
        student.parentName,
        student.phone,
        month.monthLabel,
        month.dueDate ? new Date(month.dueDate).toLocaleDateString("en-IN") : "—",
        Number(month.totalDue) || 0,
        Number(month.paidAmount) || 0,
        Number(month.endingBalance) || 0,
        getStatusLabel(month.status),
      ]);
    });
  });

  const ledgerSheet = XLSX.utils.aoa_to_sheet([ledgerHeader, ...ledgerRows]);
  ledgerSheet["!cols"] = [
    { wch: 26 },
    { wch: 12 },
    { wch: 24 },
    { wch: 14 },
    { wch: 12 },
    { wch: 14 },
    { wch: 14 },
    { wch: 14 },
    { wch: 14 },
    { wch: 10 },
  ];
  for (let r = 1; r <= ledgerRows.length; r += 1) {
    [6, 7, 8].forEach((c) => {
      const ref = XLSX.utils.encode_cell({ c, r });
      if (ledgerSheet[ref] && typeof ledgerSheet[ref].v === "number") {
        ledgerSheet[ref].z = currencyFmt;
      }
    });
  }
  ledgerSheet["!freeze"] = { xSplit: 0, ySplit: 1 };
  XLSX.utils.book_append_sheet(wb, ledgerSheet, "Detailed Ledger");

  const fileName = `monthly-fees-${sanitizeFileName(classLabel)}-${formatDateForFile()}.xlsx`;
  XLSX.writeFile(wb, fileName);
};

